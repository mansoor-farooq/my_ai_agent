param(
  [ValidateSet('Antigravity', 'Folder')]
  [string]$Agent = 'Antigravity',
  [string]$TargetDir,
  [switch]$RestoreNativeHistory,
  [switch]$SkipHermes
)

$ErrorActionPreference = 'Stop'
$hub = Split-Path -Parent $MyInvocation.MyCommand.Path
$bundle = Join-Path $hub 'agents\Antigravity\antigravity-portable-setup.zip'
$contextZip = Join-Path $hub 'shared\knowledge\readable-chat-context.zip'
$datasets = Join-Path $hub 'shared\knowledge\datasets'
if (-not (Test-Path -LiteralPath $bundle)) { throw "Missing agent bundle: $bundle" }
if (-not (Test-Path -LiteralPath $contextZip)) { throw "Missing shared context: $contextZip" }
if (-not (Test-Path -LiteralPath $datasets)) { throw "Missing project flow datasets: $datasets" }

function Install-Datasets([string]$ContextDir) {
  $destination = Join-Path $ContextDir 'datasets'
  New-Item -ItemType Directory -Path $destination -Force | Out-Null
  foreach ($item in Get-ChildItem -LiteralPath $datasets -Force) {
    $targetItem = Join-Path $destination $item.Name
    if (Test-Path -LiteralPath $targetItem) { continue }
    Copy-Item -LiteralPath $item.FullName -Destination $targetItem -Recurse
  }
}

$scratch = Join-Path ([IO.Path]::GetTempPath()) ('agents-hub-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $scratch | Out-Null
try {
  Expand-Archive -LiteralPath $bundle -DestinationPath $scratch

  if ($Agent -eq 'Antigravity') {
    & (Join-Path $scratch 'install-windows.ps1') -InstallGlobalInstructions
    & (Join-Path $scratch 'install-chat-context.ps1')
    Install-Datasets (Join-Path $env:USERPROFILE '.gemini\agent-context')

    $customAgents = Join-Path $hub 'agents\Antigravity\custom-agents'
    $agentDestination = Join-Path $env:USERPROFILE '.gemini\config\agents'
    New-Item -ItemType Directory -Path $agentDestination -Force | Out-Null
    $installedAgents = 0
    foreach ($definition in Get-ChildItem -LiteralPath $customAgents -Directory) {
      $targetAgent = Join-Path $agentDestination $definition.Name
      if (Test-Path -LiteralPath $targetAgent) {
        Write-Output "SKIP existing custom agent: $($definition.Name)"
        continue
      }
      Copy-Item -LiteralPath $definition.FullName -Destination $targetAgent -Recurse
      $installedAgents++
    }

    # Keep one manager and update the two persistent specialist profiles from this hub.
    foreach ($profileName in @('production-orchestrator', 'saas-architect', 'mansoor-ui-specialist')) {
      $targetProfile = Join-Path (Join-Path $agentDestination $profileName) 'agent.md'
      New-Item -ItemType Directory -Path (Split-Path -Parent $targetProfile) -Force | Out-Null
      Copy-Item -LiteralPath (Join-Path (Join-Path $customAgents $profileName) 'agent.md') -Destination $targetProfile -Force
    }

    # Retire only the three exact peer profiles generated by the previous backend/ML pack.
    $retiredProfiles = @{
      'node-backend-specialist' = 'Node.js and TypeScript backend specialist for service architecture, APIs, security, persistence, workers and production operations.'
      'python-backend-specialist' = 'Python backend specialist for FastAPI/Django services, typed contracts, async execution, persistence, testing and deployment.'
      'ml-pytorch-specialist' = 'ML/PyTorch specialist for data quality, training, evaluation, serving, reproducibility and MLOps integration.'
    }
    $agentRootPrefix = [IO.Path]::GetFullPath($agentDestination).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    foreach ($retired in $retiredProfiles.GetEnumerator()) {
      $oldDefinition = Join-Path (Join-Path $agentDestination $retired.Key) 'agent.md'
      if (-not (Test-Path -LiteralPath $oldDefinition)) { continue }
      $resolvedDefinition = [IO.Path]::GetFullPath($oldDefinition)
      $oldText = Get-Content -LiteralPath $resolvedDefinition -Raw
      if ($resolvedDefinition.StartsWith($agentRootPrefix, [StringComparison]::OrdinalIgnoreCase) -and
          $oldText.Contains("name: $($retired.Key)") -and $oldText.Contains("description: $($retired.Value)")) {
        Remove-Item -LiteralPath $resolvedDefinition -Force
        Write-Output "Retired superseded peer profile: $($retired.Key)"
      }
    }

    $sourceSkills = Join-Path $hub 'skills'
    $skillDestination = Join-Path $env:USERPROFILE '.gemini\config\skills'
    $managedSkillDocs = @('autonomous-deep-researcher', 'backend-ml-skill-router', 'workflow-source-research')
    New-Item -ItemType Directory -Path $skillDestination -Force | Out-Null
    $installedSkills = 0
    $updatedSkills = 0
    if (Test-Path -LiteralPath $sourceSkills) {
      foreach ($skill in Get-ChildItem -LiteralPath $sourceSkills -Directory) {
        $targetSkill = Join-Path $skillDestination $skill.Name
        if (-not (Test-Path -LiteralPath $targetSkill)) {
          Copy-Item -LiteralPath $skill.FullName -Destination $targetSkill -Recurse
          $installedSkills++
        } elseif ($managedSkillDocs -contains $skill.Name) {
          $sourceSkillDoc = Join-Path $skill.FullName 'SKILL.md'
          $targetSkillDoc = Join-Path $targetSkill 'SKILL.md'
          if ((Test-Path -LiteralPath $sourceSkillDoc) -and (Test-Path -LiteralPath $targetSkillDoc)) {
            $sourceHash = (Get-FileHash -LiteralPath $sourceSkillDoc -Algorithm SHA256).Hash
            $targetHash = (Get-FileHash -LiteralPath $targetSkillDoc -Algorithm SHA256).Hash
            if ($sourceHash -ne $targetHash) {
              $backupStamp = Get-Date -Format 'yyyyMMdd-HHmmss'
              $backupDir = Join-Path $env:USERPROFILE ".gemini\agent-context\agent-hub-backups\skills\$($skill.Name)\$backupStamp"
              New-Item -ItemType Directory -Path $backupDir -Force | Out-Null
              Copy-Item -LiteralPath $targetSkillDoc -Destination (Join-Path $backupDir 'SKILL.md')
              Copy-Item -LiteralPath $sourceSkillDoc -Destination $targetSkillDoc -Force
              $updatedSkills++
              Write-Output "Updated hub-managed skill document: $($skill.Name) (backup: $backupDir)"
            }
          }
        }
      }
    }

    $runtimeDestination = Join-Path $env:USERPROFILE '.gemini\agent-context\agent-hub-tools'
    New-Item -ItemType Directory -Path $runtimeDestination -Force | Out-Null
    Copy-Item -LiteralPath (Join-Path $hub 'tools\sync-knowledge-bank.mjs') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'tools\validate-capability-manifest.mjs') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'tools\route-backend-ml-task.mjs') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'AGENT_EXPORT_POLICY.md') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'shared\knowledge\PROJECT_MEMORY_SCHEMA.md') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'shared\control-plane') -Destination (Join-Path $runtimeDestination 'control-plane') -Recurse -Force

    # Install DeepSeek Hermes credentials and subagent runner bridge
    $hermesBridgeScript = Join-Path $hub 'subagents\deepseek-hermes\install-hermes-bridge.ps1'
    if (-not $SkipHermes -and (Test-Path -LiteralPath $hermesBridgeScript)) {
      & $hermesBridgeScript
    } elseif ($SkipHermes) {
      Write-Output 'DeepSeek Hermes setup skipped by -SkipHermes.'
    }

    if ($RestoreNativeHistory) { & (Join-Path $hub 'restore-native-history.ps1') }

    $instructions = Join-Path $env:USERPROFILE '.gemini\GEMINI.md'
    $marker = '<!-- agents-hub-context -->'
    $contextNote = @"

$marker
For existing projects, read %USERPROFILE%\.gemini\agent-context\datasets\WORKSTYLE.md and PROJECT_FLOWS.md, then read DEEPSEEK_HERMES_HANDOFF.md when delegating to Hermes. Read the relevant summary in codex-memory. Search codex-conversation-index.json and conversation-index.json in that context folder for matching chats. Read their transcripts when needed. Treat old chats as history and verify current files before editing. The project-memory sync tool is installed under %USERPROFILE%\.gemini\agent-context\agent-hub-tools and must follow AGENT_EXPORT_POLICY.md. Use production-orchestrator as the sole manager. For backend/ML work, run route-backend-ml-task.mjs from agent-hub-tools with --root %USERPROFILE%\.gemini\config; load only selected skills from the global skills directory and use task-scoped subagent invocations rather than persistent peer profiles. Maintain each project's local .agents/memory and sync only approved sanitized notes.
"@
    if (Test-Path -LiteralPath $instructions) {
      $current = Get-Content -LiteralPath $instructions -Raw
      if (-not $current.Contains($marker)) {
        Add-Content -LiteralPath $instructions -Value $contextNote
      }
      $current = Get-Content -LiteralPath $instructions -Raw
      $routingMarker = '<!-- agents-hub-manager-routing -->'
      $routingEndMarker = '<!-- /agents-hub-manager-routing -->'
      $routingNote = @"
$routingMarker
Use production-orchestrator as the only manager. Backend/ML skills are globally installed under %USERPROFILE%\.gemini\config\skills. Run route-backend-ml-task.mjs from %USERPROFILE%\.gemini\agent-context\agent-hub-tools with --root %USERPROFILE%\.gemini\config, then read only the selected skill files. Consult saas-architect for backend architecture, enterprise-schema-architect for schema work, and mansoor-ui-specialist for UI scope. Use invoke_subagent for temporary task-scoped builders and an independent verifier; do not create persistent Node/Python/ML peer profiles. For each project, keep a separate local .agents/memory with verified map, plan/flow, decisions and evidence; sync only sanitized notes allowed by AGENT_EXPORT_POLICY.md. Never store hidden chain-of-thought. Respect provider plan limits; do not cycle accounts or keys to evade quotas.
$routingEndMarker
"@
      $routingStartIndex = $current.IndexOf($routingMarker, [StringComparison]::Ordinal)
      if ($routingStartIndex -ge 0) {
        $routingEndIndex = $current.IndexOf($routingEndMarker, $routingStartIndex, [StringComparison]::Ordinal)
        $prefix = $current.Substring(0, $routingStartIndex).TrimEnd()
        $suffix = if ($routingEndIndex -ge 0) { $current.Substring($routingEndIndex + $routingEndMarker.Length) } else { '' }
        Set-Content -LiteralPath $instructions -Value ($prefix + "`r`n`r`n" + $routingNote.Trim() + $suffix) -Encoding utf8
      } else {
        Add-Content -LiteralPath $instructions -Value ("`r`n" + $routingNote.Trim() + "`r`n")
      }
    } else {
      New-Item -ItemType Directory -Path (Split-Path -Parent $instructions) -Force | Out-Null
      Set-Content -LiteralPath $instructions -Value ($contextNote.TrimStart() + "`r`n" + $routingNote.Trim()) -Encoding utf8
    }
    Write-Output "Antigravity skills installed ($installedSkills new, $updatedSkills hub-managed docs updated), chat context refreshed, and $installedAgents new custom agents installed. Restart Antigravity."
  } else {
    if ([string]::IsNullOrWhiteSpace($TargetDir)) { throw '-TargetDir is required for -Agent Folder.' }
    $target = [IO.Path]::GetFullPath($TargetDir)
    New-Item -ItemType Directory -Path $target -Force | Out-Null
    $knowledge = Join-Path $target 'agent-context'
    if (Test-Path -LiteralPath $knowledge) {
      Write-Output "SKIP existing context: $knowledge"
    } else {
      Expand-Archive -LiteralPath $contextZip -DestinationPath $knowledge
      Write-Output "Installed shared chat context: $knowledge"
    }
    Install-Datasets $knowledge
    $runtimeDestination = Join-Path $target 'agent-hub-tools'
    New-Item -ItemType Directory -Path $runtimeDestination -Force | Out-Null
    Copy-Item -LiteralPath (Join-Path $hub 'tools\sync-knowledge-bank.mjs') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'tools\validate-capability-manifest.mjs') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'tools\route-backend-ml-task.mjs') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'AGENT_EXPORT_POLICY.md') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'shared\knowledge\PROJECT_MEMORY_SCHEMA.md') -Destination $runtimeDestination -Force
    Copy-Item -LiteralPath (Join-Path $hub 'shared\control-plane') -Destination (Join-Path $runtimeDestination 'control-plane') -Recurse -Force
    $skills = Join-Path $target 'skills'
    if (Test-Path -LiteralPath $skills) {
      Write-Output "SKIP existing skills: $skills"
    } else {
      Copy-Item -LiteralPath (Join-Path $scratch 'global-skills') -Destination $skills -Recurse
      Write-Output "Copied skill references: $skills"
    }
    $pluginReferences = Join-Path $target 'plugin-skill-reference'
    if (Test-Path -LiteralPath $pluginReferences) {
      Write-Output "SKIP existing plugin references: $pluginReferences"
    } else {
      Copy-Item -LiteralPath (Join-Path $scratch 'codex-plugin-reference') -Destination $pluginReferences -Recurse
      Write-Output "Copied plugin skill references: $pluginReferences"
    }
    $handoff = Join-Path $target 'AGENT_HANDOFF.md'
    if (-not (Test-Path -LiteralPath $handoff)) {
      Copy-Item -LiteralPath (Join-Path $hub 'shared\AGENT_HANDOFF.md') -Destination $handoff
    }
    Write-Output "Folder handoff ready: $target"
  }
} finally {
  $tempRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
  $resolvedScratch = [IO.Path]::GetFullPath($scratch)
  if ($resolvedScratch.StartsWith($tempRoot, [StringComparison]::OrdinalIgnoreCase) -and
      (Split-Path -Leaf $resolvedScratch).StartsWith('agents-hub-', [StringComparison]::OrdinalIgnoreCase) -and
      (Test-Path -LiteralPath $resolvedScratch)) {
    Remove-Item -LiteralPath $resolvedScratch -Recurse -Force
  }
}
